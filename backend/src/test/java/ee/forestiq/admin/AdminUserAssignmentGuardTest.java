package ee.forestiq.admin;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.jooq.impl.DSL.field;
import static org.jooq.impl.DSL.table;

import java.util.UUID;

import org.jooq.DSLContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.web.server.ResponseStatusException;

import ee.forestiq.support.H2JooqTestDatabase;

class AdminUserAssignmentGuardTest {
    private static final UUID ORG = UUID.fromString("11111111-1111-1111-1111-111111111111");
    private static final String USER = "subject-a";

    private H2JooqTestDatabase database;
    private DSLContext dsl;
    private AdminUserAssignmentGuard guard;

    @BeforeEach
    void setUp() throws Exception {
        database = H2JooqTestDatabase.create("admin-user-impact-" + UUID.randomUUID());
        dsl = database.dsl();
        dsl.execute("create table owner (id uuid primary key, organization_id uuid not null, assigned_to_subject varchar(100))");
        dsl.execute("create table inheritance_case (id uuid primary key, organization_id uuid not null, assigned_to_subject varchar(100))");
        dsl.execute("create table deal_case (id uuid primary key, organization_id uuid not null, evaluator_subject varchar(100))");
        dsl.execute("create table owner_following (owner_id uuid not null, user_subject varchar(100), primary key (owner_id, user_subject))");
        dsl.execute("create table reminder (id bigint generated by default as identity primary key, organization_id uuid not null, creator varchar(100))");
        guard = new AdminUserAssignmentGuard(dsl);
    }

    @AfterEach
    void tearDown() throws Exception { database.close(); }

    @Test
    void activeAssignmentsBlockDeletionAndExposeImpactCounts() {
        UUID ownerId = UUID.randomUUID();
        dsl.insertInto(table("owner")).columns(field("id"), field("organization_id"), field("assigned_to_subject"))
            .values(ownerId, ORG, USER).execute();
        dsl.insertInto(table("inheritance_case")).columns(field("id"), field("organization_id"), field("assigned_to_subject"))
            .values(UUID.randomUUID(), ORG, USER).execute();
        dsl.insertInto(table("deal_case")).columns(field("id"), field("organization_id"), field("evaluator_subject"))
            .values(UUID.randomUUID(), ORG, USER).execute();
        dsl.insertInto(table("owner_following")).columns(field("owner_id"), field("user_subject"))
            .values(ownerId, USER).execute();
        dsl.insertInto(table("reminder")).columns(field("organization_id"), field("creator"))
            .values(ORG, USER).execute();

        var impact = guard.impact(ORG, USER);
        assertThat(impact.owners()).isOne();
        assertThat(impact.inheritanceCases()).isOne();
        assertThat(impact.evaluatorDeals()).isOne();
        assertThat(impact.followedOwners()).isOne();
        assertThat(impact.reminders()).isOne();
        assertThat(impact.blockingAssignments()).isEqualTo(5);
        assertThat(impact.safeToDelete()).isFalse();
        assertThatThrownBy(() -> guard.requireSafeToDelete(ORG, USER))
            .isInstanceOf(ResponseStatusException.class).hasMessageContaining("409 CONFLICT");
    }

    @Test
    void followedOwnersAreScopedThroughOwnerOrganization() {
        UUID otherOrg = UUID.fromString("22222222-2222-2222-2222-222222222222");
        UUID ownOwnerId = UUID.randomUUID();
        UUID otherOwnerId = UUID.randomUUID();

        dsl.insertInto(table("owner")).columns(field("id"), field("organization_id"), field("assigned_to_subject"))
            .values(ownOwnerId, ORG, null).execute();
        dsl.insertInto(table("owner")).columns(field("id"), field("organization_id"), field("assigned_to_subject"))
            .values(otherOwnerId, otherOrg, null).execute();
        dsl.insertInto(table("owner_following")).columns(field("owner_id"), field("user_subject"))
            .values(ownOwnerId, USER).execute();
        dsl.insertInto(table("owner_following")).columns(field("owner_id"), field("user_subject"))
            .values(otherOwnerId, USER).execute();

        assertThat(guard.impact(ORG, USER).followedOwners()).isOne();
        assertThat(guard.impact(otherOrg, USER).followedOwners()).isOne();
    }

    @Test
    void unrelatedOrganizationDoesNotBlockDeletion() {
        UUID otherOrg = UUID.fromString("22222222-2222-2222-2222-222222222222");
        dsl.insertInto(table("owner")).columns(field("id"), field("organization_id"), field("assigned_to_subject"))
            .values(UUID.randomUUID(), otherOrg, USER).execute();

        assertThat(guard.impact(ORG, USER).safeToDelete()).isTrue();
        guard.requireSafeToDelete(ORG, USER);
    }
}
