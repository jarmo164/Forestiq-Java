package ee.forestiq.reminder;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.jooq.impl.DSL.count;
import static org.jooq.impl.DSL.field;
import static org.jooq.impl.DSL.name;
import static org.jooq.impl.DSL.table;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.time.Instant;
import java.util.List;
import java.util.UUID;

import org.jooq.DSLContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.web.server.ResponseStatusException;

import ee.forestiq.owner.OwnerAuthorizationService;
import ee.forestiq.owner.OwnerDtos.CreateReminderRequest;
import ee.forestiq.security.OrganizationContext;
import ee.forestiq.support.H2JooqTestDatabase;

@ExtendWith(MockitoExtension.class)
class ReminderServiceTest {

    private static final UUID ORG_A = UUID.fromString("11111111-1111-1111-1111-111111111111");
    private static final UUID ORG_B = UUID.fromString("aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa");
    private static final UUID OWNER_A = UUID.fromString("22222222-2222-2222-2222-222222222222");
    private static final UUID OWNER_B = UUID.fromString("bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb");
    private static final UUID PARCEL_A = UUID.fromString("33333333-3333-3333-3333-333333333333");
    private static final String CADASTRAL_CODE = "78401:101:0101";

    @Mock private OrganizationContext organizationContext;
    @Mock private OwnerAuthorizationService ownerAuthorizationService;

    private H2JooqTestDatabase database;
    private DSLContext dsl;
    private ReminderService service;

    @BeforeEach
    void setUp() throws Exception {
        database = H2JooqTestDatabase.create("reminders-" + UUID.randomUUID());
        dsl = database.dsl();
        dsl.execute("""
            create table owner (
                id uuid primary key,
                organization_id uuid not null,
                display_name varchar(300) not null,
                assigned_to_subject varchar(100)
            )
            """);
        dsl.execute("""
            create table land_parcel (
                id uuid primary key,
                organization_id uuid not null,
                cadastral_code varchar(32) not null
            )
            """);
        dsl.execute("""
            create table owner_parcel_relation (
                organization_id uuid not null,
                owner_id uuid not null,
                parcel_id uuid not null,
                active boolean not null
            )
            """);
        dsl.execute("""
            create table reminder (
                id bigint generated by default as identity primary key,
                organization_id uuid not null,
                creator varchar(100) not null,
                owner_id uuid,
                cadastral_code varchar(32),
                property_name varchar(300),
                reminder_text varchar(500) not null,
                due_time timestamp with time zone not null,
                created_at timestamp with time zone not null default current_timestamp
            )
            """);
        service = new ReminderService(dsl, organizationContext, ownerAuthorizationService);
    }

    @AfterEach
    void tearDown() throws Exception {
        database.close();
    }

    @Test
    void createRejectsReminderForOwnerOutsideAuthenticatedOrganization() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG_A);
        when(organizationContext.subject()).thenReturn("caller-a");
        insertOwner(ORG_B, OWNER_B, "Other Org Owner", "caller-b");

        assertThatThrownBy(() -> service.create(new CreateReminderRequest("Call owner", Instant.parse("2026-08-20T10:00:00Z"), OWNER_B, null)))
            .isInstanceOf(ResponseStatusException.class)
            .hasMessageContaining("Owner does not belong to the organization");

        assertThat(reminderCount()).isZero();
    }

    @Test
    void callerCannotCreateReminderForOwnerAssignedToAnotherCaller() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG_A);
        when(organizationContext.subject()).thenReturn("caller-a");
        insertOwner(ORG_A, OWNER_A, "Current Org Owner", "caller-b");
        doThrow(new AccessDeniedException("Owner is not assigned to the current caller"))
            .when(ownerAuthorizationService).assertCanMutateAssignedSubject("caller-b");

        assertThatThrownBy(() -> service.create(new CreateReminderRequest("Call owner", Instant.parse("2026-08-20T10:00:00Z"), OWNER_A, null)))
            .isInstanceOf(AccessDeniedException.class);

        assertThat(reminderCount()).isZero();
    }

    @Test
    void createAuthorizesBothOwnerAndCadastreAssignments() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG_A);
        when(organizationContext.subject()).thenReturn("caller-a");
        insertOwner(ORG_A, OWNER_A, "Current Org Owner", "caller-a");
        insertParcelRelation();

        service.create(new CreateReminderRequest("Call owner", Instant.parse("2026-08-20T10:00:00Z"), OWNER_A, CADASTRAL_CODE));

        assertThat(reminderCount()).isOne();
        verify(ownerAuthorizationService).assertCanMutateAssignedSubject("caller-a");
        verify(ownerAuthorizationService).assertCanMutateAnyAssignedSubject(List.of("caller-a"));
    }

    @Test
    void listDoesNotResolveOwnerNameAcrossOrganizations() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG_A);
        when(organizationContext.subject()).thenReturn("caller-a");
        insertOwner(ORG_B, OWNER_B, "Other Org Owner", "caller-b");
        dsl.insertInto(table("reminder"))
            .columns(field(name("organization_id")), field(name("creator")), field(name("owner_id")),
                field(name("reminder_text")), field(name("due_time")))
            .values(ORG_A, "caller-a", OWNER_B, "Cross tenant fixture", Instant.parse("2026-08-20T10:00:00Z"))
            .execute();

        var reminders = service.getMyReminders();

        assertThat(reminders).hasSize(1);
        assertThat(reminders.getFirst().ownerId()).isEqualTo(OWNER_B);
        assertThat(reminders.getFirst().ownerName()).isNull();
    }

    @Test
    void callerCannotDeleteAnotherUsersReminder() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG_A);
        when(organizationContext.subject()).thenReturn("caller-a");
        Long reminder = insertReminder(ORG_A, "caller-b", null, "Other caller reminder");

        assertThatThrownBy(() -> service.delete(reminder))
            .isInstanceOf(ResponseStatusException.class)
            .hasMessageContaining("404");
        assertThat(reminderCount()).isOne();
    }

    @Test
    void deleteOwnReminderSucceeds() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG_A);
        when(organizationContext.subject()).thenReturn("caller-a");
        Long reminder = insertReminder(ORG_A, "caller-a", null, "My reminder");

        service.delete(reminder);

        assertThat(reminderCount()).isZero();
    }

    private void insertOwner(UUID organizationId, UUID ownerId, String displayName, String assignedSubject) {
        dsl.insertInto(table("owner"))
            .columns(field(name("id")), field(name("organization_id")), field(name("display_name")), field(name("assigned_to_subject")))
            .values(ownerId, organizationId, displayName, assignedSubject)
            .execute();
    }

    private void insertParcelRelation() {
        dsl.insertInto(table("land_parcel"))
            .columns(field(name("id")), field(name("organization_id")), field(name("cadastral_code")))
            .values(PARCEL_A, ORG_A, CADASTRAL_CODE)
            .execute();
        dsl.insertInto(table("owner_parcel_relation"))
            .columns(field(name("organization_id")), field(name("owner_id")), field(name("parcel_id")), field(name("active")))
            .values(ORG_A, OWNER_A, PARCEL_A, true)
            .execute();
    }

    private Long insertReminder(UUID organizationId, String creator, UUID ownerId, String text) {
        return dsl.insertInto(table("reminder"))
            .columns(field(name("organization_id")), field(name("creator")), field(name("owner_id")),
                field(name("reminder_text")), field(name("due_time")))
            .values(organizationId, creator, ownerId, text, Instant.parse("2026-08-20T10:00:00Z"))
            .returningResult(field(name("id"), Long.class))
            .fetchOneInto(Long.class);
    }

    private int reminderCount() {
        return dsl.select(count()).from(table("reminder")).fetchOneInto(Integer.class);
    }
}
