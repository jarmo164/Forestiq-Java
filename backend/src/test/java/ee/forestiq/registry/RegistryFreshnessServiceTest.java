package ee.forestiq.registry;

import static org.assertj.core.api.Assertions.assertThat;
import static org.jooq.impl.DSL.field;
import static org.jooq.impl.DSL.name;
import static org.jooq.impl.DSL.table;
import static org.mockito.Mockito.mock;

import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

import org.jooq.DSLContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import ee.forestiq.security.OrganizationContext;
import ee.forestiq.support.H2JooqTestDatabase;

class RegistryFreshnessServiceTest {

    private static final UUID ORG_A = UUID.fromString("11111111-1111-1111-1111-111111111111");
    private static final UUID ORG_B = UUID.fromString("22222222-2222-2222-2222-222222222222");
    private static final UUID OWNER_A = UUID.fromString("33333333-3333-3333-3333-333333333333");
    private static final UUID OWNER_B = UUID.fromString("44444444-4444-4444-4444-444444444444");

    private H2JooqTestDatabase database;
    private DSLContext dsl;

    @BeforeEach
    void setUp() throws Exception {
        database = H2JooqTestDatabase.create("registry-freshness-" + UUID.randomUUID());
        dsl = database.dsl();
        dsl.execute("""
            create table land_parcel (
                id uuid primary key,
                organization_id uuid not null,
                owner_id uuid not null,
                cadastral_code varchar(40) not null,
                name varchar(200),
                updated_at timestamp with time zone
            )
            """);
        dsl.execute("""
            create table registry_sync_log (
                id bigint generated by default as identity primary key,
                organization_id uuid not null,
                cadastral_code varchar(40) not null,
                registry_name varchar(80) not null,
                status varchar(32) not null,
                created_at timestamp with time zone not null
            )
            """);
        dsl.execute("""
            create table data_change_signal (
                id bigint generated by default as identity primary key,
                organization_id uuid not null,
                dismissed_at timestamp with time zone
            )
            """);
        dsl.execute("""
            create table geospatial_generation (
                id uuid primary key,
                source_key varchar(128) not null,
                source_date date,
                published_at timestamp with time zone
            )
            """);
        dsl.execute("""
            create table geospatial_source_current (
                source_key varchar(128) primary key,
                generation_id uuid not null,
                published_at timestamp with time zone not null
            )
            """);
    }

    @AfterEach
    void tearDown() throws Exception {
        database.close();
    }

    @Test
    void dashboardIsOrganizationScopedAndSeparatesFreshAndStaleSources() {
        insertParcel(ORG_A, OWNER_A, "12345:001:0001", "A parcel");
        insertParcel(ORG_A, OWNER_A, "12345:001:0002", "A stale parcel");
        insertParcel(ORG_B, OWNER_B, "99999:001:0001", "B parcel");

        Instant fresh = Instant.now().minusSeconds(60);
        insertSync(ORG_A, "12345:001:0001", "MAAAMET_WFS", "SUCCESS", fresh);
        insertSync(ORG_A, "12345:001:0001", "METSAREGISTER_TEATISED", "SUCCESS", fresh);
        insertSync(ORG_A, "12345:001:0001", "METSAREGISTER_ERALDISED", "SUCCESS", fresh);
        insertSync(ORG_A, "12345:001:0002", "MAAAMET_WFS", "FAILED", fresh);
        insertSync(ORG_B, "99999:001:0001", "MAAAMET_WFS", "SUCCESS", fresh);

        dsl.insertInto(table("data_change_signal"))
            .columns(field(name("organization_id")), field(name("dismissed_at")))
            .values(ORG_A, null)
            .values(ORG_B, null)
            .execute();

        RegistryProperties properties = new RegistryProperties();
        properties.getAutoRefresh().setCadastreMaxAgeHours(168);
        properties.getAutoRefresh().setForestMaxAgeHours(24);
        RegistryFreshnessService service = new RegistryFreshnessService(
            dsl, mock(OrganizationContext.class), properties, mock(RegistrySyncService.class));

        var dashboard = service.dashboardForOrganization(ORG_A);

        assertThat(dashboard.openDataSignals()).isEqualTo(1);
        assertThat(dashboard.sources()).hasSize(3);
        assertThat(dashboard.sources()).allSatisfy(source -> assertThat(source.totalParcels()).isEqualTo(2));
        assertThat(dashboard.sources()).filteredOn(source -> source.registry().equals("MAAAMET_WFS"))
            .singleElement()
            .satisfies(source -> {
                assertThat(source.freshParcels()).isEqualTo(1);
                assertThat(source.staleParcels()).isEqualTo(1);
                assertThat(source.failuresLast24Hours()).isEqualTo(1);
            });
        assertThat(dashboard.staleParcels()).extracting(RegistryFreshnessService.StaleParcel::cadastralCode)
            .contains("12345:001:0002")
            .doesNotContain("99999:001:0001");
    }

    @Test
    void cadastreFreshnessUsesCurrentSourceGenerationBeforeLegacyWfsHistory() {
        insertParcel(ORG_A, OWNER_A, "12345:001:0001", "A parcel");
        insertParcel(ORG_A, OWNER_A, "12345:001:0002", "Another parcel");
        UUID generationId = UUID.randomUUID();
        Instant publishedAt = Instant.now().minusSeconds(30);
        dsl.insertInto(table("geospatial_generation"))
            .columns(field(name("id")), field(name("source_key")), field(name("source_date")),
                field(name("published_at")))
            .values(generationId, "MARU_CADASTRE", LocalDate.of(2026, 9, 9), publishedAt)
            .execute();
        dsl.insertInto(table("geospatial_source_current"))
            .columns(field(name("source_key")), field(name("generation_id")), field(name("published_at")))
            .values("MARU_CADASTRE", generationId, publishedAt)
            .execute();
        insertSync(ORG_A, "12345:001:0001", "METSAREGISTER_TEATISED", "SUCCESS", Instant.now());
        insertSync(ORG_A, "12345:001:0001", "METSAREGISTER_ERALDISED", "SUCCESS", Instant.now());
        insertSync(ORG_A, "12345:001:0002", "METSAREGISTER_TEATISED", "SUCCESS", Instant.now());
        insertSync(ORG_A, "12345:001:0002", "METSAREGISTER_ERALDISED", "SUCCESS", Instant.now());

        RegistryProperties properties = new RegistryProperties();
        RegistryFreshnessService service = new RegistryFreshnessService(
            dsl, mock(OrganizationContext.class), properties, mock(RegistrySyncService.class));

        var dashboard = service.dashboardForOrganization(ORG_A);

        assertThat(dashboard.sources()).filteredOn(source -> source.registry().equals("MAAAMET_WFS"))
            .singleElement()
            .satisfies(source -> {
                assertThat(source.evidence()).isEqualTo("SOURCE_GENERATION");
                assertThat(source.generationId()).isEqualTo(generationId.toString());
                assertThat(source.sourceDate()).isEqualTo("2026-09-09");
                assertThat(source.freshParcels()).isEqualTo(2);
                assertThat(source.staleParcels()).isZero();
            });
        assertThat(dashboard.staleParcels()).isEmpty();
    }

    private void insertParcel(UUID orgId, UUID ownerId, String cadastralCode, String parcelName) {
        dsl.insertInto(table("land_parcel"))
            .columns(field(name("id")), field(name("organization_id")), field(name("owner_id")),
                field(name("cadastral_code")), field(name("name")), field(name("updated_at")))
            .values(UUID.randomUUID(), orgId, ownerId, cadastralCode, parcelName, Instant.now())
            .execute();
    }

    private void insertSync(UUID orgId, String cadastralCode, String registry, String status, Instant createdAt) {
        dsl.insertInto(table("registry_sync_log"))
            .columns(field(name("organization_id")), field(name("cadastral_code")), field(name("registry_name")),
                field(name("status")), field(name("created_at")))
            .values(orgId, cadastralCode, registry, status, createdAt)
            .execute();
    }
}
