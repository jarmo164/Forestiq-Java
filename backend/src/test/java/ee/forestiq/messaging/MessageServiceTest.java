package ee.forestiq.messaging;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.jooq.impl.DSL.count;
import static org.jooq.impl.DSL.table;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.when;

import java.time.Instant;
import java.util.List;
import java.util.Set;
import java.util.UUID;

import org.jooq.DSLContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import ee.forestiq.identity.OrganizationIdentityDirectory;
import ee.forestiq.identity.OrganizationRole;
import ee.forestiq.identity.OrganizationUser;
import ee.forestiq.owner.OwnerDtos.SendMessageRequest;
import ee.forestiq.security.OrganizationContext;
import ee.forestiq.support.H2JooqTestDatabase;

@ExtendWith(MockitoExtension.class)
class MessageServiceTest {

    private static final UUID ORG = UUID.fromString("11111111-1111-1111-1111-111111111111");
    private static final UUID OTHER_ORG = UUID.fromString("22222222-2222-2222-2222-222222222222");

    @Mock private OrganizationContext organizationContext;
    @Mock private OrganizationIdentityDirectory identityDirectory;

    private H2JooqTestDatabase database;
    private DSLContext dsl;
    private MessageService service;

    @BeforeEach
    void setUp() throws Exception {
        database = H2JooqTestDatabase.create("messages-" + UUID.randomUUID());
        dsl = database.dsl();
        dsl.execute("""
            create table message (
                id bigint generated by default as identity primary key,
                organization_id uuid not null,
                sender varchar(200) not null,
                recipient varchar(200) not null,
                message_text varchar(4000) not null,
                created_at timestamp with time zone not null default current_timestamp,
                noticed_at timestamp with time zone
            )
            """);
        service = new MessageService(dsl, organizationContext, identityDirectory);
    }

    @AfterEach
    void tearDown() throws Exception {
        database.close();
    }

    @Test
    void unknownRecipientIsRejectedBeforeInsert() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG);
        doThrow(new ResponseStatusException(HttpStatus.BAD_REQUEST, "unknown user"))
            .when(identityDirectory).requireActiveOrganizationUser(ORG, "missing-subject");

        assertThatThrownBy(() -> service.send(new SendMessageRequest("missing-subject", "hello")))
            .isInstanceOf(ResponseStatusException.class);
        assertThat(dsl.select(count()).from(table("message")).fetchOneInto(Integer.class)).isZero();
    }

    @Test
    void activeRecipientCanReceiveMessage() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG);
        when(organizationContext.subject()).thenReturn("sender-subject");
        when(identityDirectory.requireActiveOrganizationUser(ORG, "recipient-subject"))
            .thenReturn(new OrganizationUser("recipient-subject", "receiver", "Receiver", Set.of(OrganizationRole.CALLER)));

        service.send(new SendMessageRequest(" recipient-subject ", " hello "));

        assertThat(dsl.select(count()).from(table("message")).fetchOneInto(Integer.class)).isOne();
        assertThat(dsl.fetchOne("select recipient from message").get(0, String.class)).isEqualTo("recipient-subject");
        assertThat(dsl.fetchOne("select message_text from message").get(0, String.class)).isEqualTo("hello");
    }

    @Test
    void sameSubjectCannotReadCountOrNoticeMessagesFromAnotherOrganization() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG);
        when(organizationContext.subject()).thenReturn("shared-subject");
        Instant createdAt = Instant.parse("2026-08-26T00:00:00Z");
        dsl.execute("""
            insert into message (organization_id, sender, recipient, message_text, created_at)
            values (?, 'sender-a', 'shared-subject', 'org-a-message', ?),
                   (?, 'sender-b', 'shared-subject', 'org-b-message', ?)
            """, ORG, createdAt, OTHER_ORG, createdAt);

        assertThat(service.received(0, 20))
            .extracting(message -> message.message())
            .containsExactly("org-a-message");
        assertThat(service.unnoticedCount()).isEqualTo(1L);

        service.markNoticed(createdAt.plusSeconds(1));

        assertThat(service.unnoticedCount()).isZero();
        Boolean otherStillUnnoticed = dsl.fetchOne(
            "select noticed_at is null from message where organization_id = ?", OTHER_ORG)
            .get(0, Boolean.class);
        assertThat(otherStillUnnoticed).isTrue();
    }

    @Test
    void invalidPagingIsRejectedBeforeSql() {
        assertThatThrownBy(() -> service.received(-1, 20)).isInstanceOf(ResponseStatusException.class);
        assertThatThrownBy(() -> service.sent(0, 101)).isInstanceOf(ResponseStatusException.class);
        assertThatThrownBy(() -> service.sent(Integer.MAX_VALUE, 100)).isInstanceOf(ResponseStatusException.class);
    }

    @Test
    void recipientPickerUsesOnlyActiveDirectoryUsers() {
        when(organizationContext.requiredOrganizationId()).thenReturn(ORG);
        when(identityDirectory.listActiveOrganizationUsers(ORG)).thenReturn(List.of(
            new OrganizationUser("active-subject", "active", "Active User", Set.of(OrganizationRole.CALLER))));

        assertThat(service.recipients()).containsExactly(java.util.Map.of("id", "active-subject", "name", "Active User"));
    }
}
